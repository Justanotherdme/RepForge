import Foundation

enum LocalizationCatalog {
    static func translate(_ english: String, language: String) -> String {
        if let value = table(for: language)[english] {
            return value
        }
        if let value = dynamicTranslation(english, language: language) {
            return value
        }
        return english
    }

    private static func table(for language: String) -> [String: String] {
        switch language {
        case "es": return es
        case "de": return de
        case "fr": return fr
        default: return [:]
        }
    }

    private static func dynamicTranslation(_ english: String, language: String) -> String? {
        if english.hasPrefix("Could not restore backup: ") {
            let detail = String(english.dropFirst("Could not restore backup: ".count))
            switch language {
            case "es": return "No se pudo restaurar la copia de seguridad: \(detail)"
            case "de": return "Backup konnte nicht wiederhergestellt werden: \(detail)"
            case "fr": return "Impossible de restaurer la sauvegarde : \(detail)"
            default: return nil
            }
        }

        if english.hasPrefix("Delete set ") {
            let value = String(english.dropFirst("Delete set ".count))
            switch language {
            case "es": return "Eliminar serie \(value)"
            case "de": return "Satz \(value) löschen"
            case "fr": return "Supprimer la série \(value)"
            default: return nil
            }
        }

        if english.hasPrefix("Set "), Int(english.dropFirst("Set ".count)) != nil {
            let value = String(english.dropFirst("Set ".count))
            switch language {
            case "es": return "Serie \(value)"
            case "de": return "Satz \(value)"
            case "fr": return "Série \(value)"
            default: return nil
            }
        }

        if english.hasPrefix("Imported template “") {
            let value = String(english.dropFirst("Imported template ".count))
            switch language {
            case "es": return "Plantilla importada \(value)"
            case "de": return "Vorlage importiert \(value)"
            case "fr": return "Modèle importé \(value)"
            default: return nil
            }
        }

        if english.hasPrefix("Imported "), english.contains(" workouts from “") {
            switch language {
            case "es":
                return english
                    .replacingOccurrences(of: "Imported ", with: "Se importaron ")
                    .replacingOccurrences(of: " workouts from ", with: " entrenamientos de ")
            case "de":
                return english
                    .replacingOccurrences(of: "Imported ", with: "")
                    .replacingOccurrences(of: " workouts from ", with: " Workouts importiert aus ")
            case "fr":
                return english
                    .replacingOccurrences(of: "Imported ", with: "")
                    .replacingOccurrences(of: " workouts from ", with: " entraînements importés depuis ")
            default:
                return nil
            }
        }

        return nil
    }

